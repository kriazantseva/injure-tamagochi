package project.model.mood;

/*enum MoodTypes contain constant types of different mood
* depends on pet's character chance to get randomly type of mood waving*/
public enum MoodTypes {
    JOYFUL, //Feeling extremely happy and full of energy
    HAPPY, //A relaxed and satisfied feeling, everything is okay
    OPTIMISTIC, //Feeling hopeful and positive about the future
    CALM, //A peaceful state, feeling relaxed and unbothered
    INSPIRED, //Feeling motivated and ready to take on new challenges
    EXCITED, //Feeling eager and enthusiastic about something upcoming
    INDIFFERENT, //A neutral state, feeling neither good nor bad
    IRRITATED, //Feeling slightly annoyed or bothered
    WORRIED, //Anxious or concerned about something
    SAD, //Feeling down or low, lacking energy
    ANGRY, //Feeling frustrated, upset, or annoyed
    HOPELESS //A deep feeling of despair and lack of motivation
}
